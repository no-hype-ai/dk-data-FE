-- =============================================================================
-- Migration 086: CMS PUF Agent Silver Table Schema Fixes
-- Feature: 019-cms-puf-platform-reconciliation
-- =============================================================================
-- Fixes discovered during agent quality review:
-- 1. All 6 hcs_silver agent tables are missing `updated_at` (agents set it in
--    ON CONFLICT UPDATE, causing runtime errors).
-- 2. hcs_silver.service_lines UNIQUE (npi, service_line, _source_year) does not
--    match ON CONFLICT (npi) in write_results — intent is one service line per NPI.
-- 3. hcs_silver.idn_hierarchy UNIQUE (child_npi, parent_organization) does not
--    match ON CONFLICT (child_npi) — intent is one parent per child NPI.
-- 4. hcs_silver.referral_network missing relationship_strength column (returned
--    by LLM, stored in output dict, never written to a queryable column).
-- 5. hcs_silver.equipment_inventory missing inferred_equipment column (same issue).
-- =============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Add updated_at to all 6 hcs_silver agent tables
-- ---------------------------------------------------------------------------

ALTER TABLE hcs_silver.service_lines
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

ALTER TABLE hcs_silver.idn_hierarchy
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

ALTER TABLE hcs_silver.referral_network
