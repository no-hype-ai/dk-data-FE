-- ---------------------------------------------------------------------------
-- 2. Fix hcs_silver.service_lines UNIQUE constraint
--    Old: UNIQUE (npi, service_line, _source_year)  — allows multiple rows per NPI
--    New: UNIQUE (npi)                               — one primary service line per NPI
-- ---------------------------------------------------------------------------

DO $$
BEGIN
    -- Drop the old composite constraint (name is auto-generated by PostgreSQL)
    IF EXISTS (
        SELECT 1 FROM information_schema.table_constraints
        WHERE table_schema = 'hcs_silver'
          AND table_name = 'service_lines'
          AND constraint_type = 'UNIQUE'
          AND constraint_name != 'service_lines_pkey'
          AND constraint_name NOT LIKE '%_npi_key'
    ) THEN
        EXECUTE (
            SELECT 'ALTER TABLE hcs_silver.service_lines DROP CONSTRAINT ' || constraint_name
            FROM information_schema.table_constraints
            WHERE table_schema = 'hcs_silver'
              AND table_name = 'service_lines'
              AND constraint_type = 'UNIQUE'
              AND constraint_name != 'service_lines_pkey'
              AND constraint_name NOT LIKE '%_npi_key'
            LIMIT 1
        );
    END IF;
END;
$$;

ALTER TABLE hcs_silver.service_lines
    ADD CONSTRAINT IF NOT EXISTS service_lines_npi_key UNIQUE (npi);

-- ---------------------------------------------------------------------------
-- 3. Fix hcs_silver.idn_hierarchy UNIQUE constraint
--    Old: UNIQUE (child_npi, parent_organization)  — allows multiple parents per child
--    New: UNIQUE (child_npi)                        — one parent per child NPI
-- ---------------------------------------------------------------------------

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.table_constraints
        WHERE table_schema = 'hcs_silver'
          AND table_name = 'idn_hierarchy'
          AND constraint_type = 'UNIQUE'
          AND constraint_name != 'idn_hierarchy_pkey'
          AND constraint_name NOT LIKE '%_child_npi_key'
    ) THEN
        EXECUTE (
            SELECT 'ALTER TABLE hcs_silver.idn_hierarchy DROP CONSTRAINT ' || constraint_name
            FROM information_schema.table_constraints
            WHERE table_schema = 'hcs_silver'
              AND table_name = 'idn_hierarchy'
              AND constraint_type = 'UNIQUE'
              AND constraint_name != 'idn_hierarchy_pkey'
              AND constraint_name NOT LIKE '%_child_npi_key'
            LIMIT 1
        );
    END IF;
END;
$$;

ALTER TABLE hcs_silver.idn_hierarchy
    ADD CONSTRAINT IF NOT EXISTS idn_hierarchy_child_npi_key UNIQUE (child_npi);

