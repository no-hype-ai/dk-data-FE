    ) AS t(who_indicator, icd10_code, metric_type, indication_label)
)

SELECT
    gen_random_uuid()   AS id,
    ir.who_indicator,
    ir.icd10_code,
    ir.metric_type,
    ir.indication_label,
    -- Enrich with ontology fields (therapeutic area, chapter, pharma flag)
    io.therapeutic_area,
    io.icd10_chapter_num,
    io.is_pharma_relevant,
    io.indication_name  AS ontology_indication_name,
    NOW()               AS created_at

FROM indicator_registry ir
LEFT JOIN ind_silver.indication_ontology io
       ON io.icd10_code = ir.icd10_code
WHERE ir.who_indicator IS NOT NULL
  AND ir.icd10_code IS NOT NULL;
