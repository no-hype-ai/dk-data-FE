-- SQLMesh Model: Silver ICD-10 ↔ WHO GHO Indicator Mapping
-- Maps WHO GHO epidemiology indicator codes to ICD-10 codes and metric types.
-- Used by mol_silver.indication_epidemiology to join GHO data to disease codes.
--
-- Source-of-truth: ind_silver.indication_ontology.gho_indicator_codes (JSONB array)
-- The full indicator-to-ICD10 mapping lives in indication_ontology as a crossref CTE.
-- This model unnests that array into one row per indicator for efficient equi-joins.
--
-- Coverage: ~300 WHO GHO indicator codes across all pharma-relevant ICD-10 chapters.

MODEL (
    name mol_silver.icd10_indicator_mapping,
    kind FULL,
    cron '@monthly',
    audits (
        not_null(columns := (who_indicator, icd10_code)),
        unique_values(columns := (who_indicator))
    ),
    grain who_indicator
);

